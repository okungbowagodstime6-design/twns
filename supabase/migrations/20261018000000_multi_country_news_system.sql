update public.news_articles
set main_category = 'breaking'
where main_category = 'general'
  and article_type in ('BREAKING', 'DEVELOPING');

update public.news_articles
set main_category = 'entertainment'
where main_category = 'general'
  and category_id = (select id from public.categories where slug = 'entertainment' limit 1);

update public.news_articles
set main_category = 'country'
where main_category = 'general'
  and country_code is not null;

update public.articles
set main_category = lower(category)
where lower(category) in ('breaking', 'entertainment', 'country');
