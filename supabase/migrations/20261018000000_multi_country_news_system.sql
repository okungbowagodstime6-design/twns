create table if not exists public.news_feeds (
  id uuid primary key default gen_random_uuid(),
  feed_name text not null,
  feed_url text not null unique,
  category text not null check (category in ('breaking', 'entertainment', 'country')),
  country_code varchar(8) not null default 'GLOBAL',
  sub_category varchar(50) not null default 'general',
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

alter table public.articles
  add column if not exists country_code varchar(8) not null default 'GLOBAL',
  add column if not exists sub_category varchar(50) not null default 'general',
  add column if not exists main_category text not null default 'general';

alter table public.news_articles
  add column if not exists sub_category varchar(50) not null default 'general',
  add column if not exists main_category text not null default 'general',
  add column if not exists source_url_hash text;

alter table public.feeds
  add column if not exists country_code varchar(8) not null default 'GLOBAL',
  add column if not exists sub_category varchar(50) not null default 'general',
  add column if not exists main_category text not null default 'general';

create index if not exists idx_articles_country_lookup
  on public.articles (country_code, main_category, sub_category);
create index if not exists idx_news_articles_country_lookup
  on public.news_articles (country_code, main_category, sub_category);
create unique index if not exists idx_news_articles_source_url_hash
  on public.news_articles (source_url_hash);
create index if not exists idx_news_feeds_active_category
  on public.news_feeds (is_active, category, country_code, sub_category);

alter table public.news_feeds enable row level security;

